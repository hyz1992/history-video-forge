<script setup lang="ts">
import { computed, onMounted, watch, ref } from "vue";
import { useRouter } from "vue-router";
import { ElMessage } from "element-plus";

import { useScriptStore } from "../../stores/script";
import { useProjectStore } from "../../stores/project";
import { useWorkspaceStore, PIPELINE_STEPS } from "../../stores/workspace";
import { useStagePolling } from "../../composables/useStagePolling";
import StageGenerating from "../workspace/StageGenerating.vue";
import StageLoadingBar from "../workspace/StageLoadingBar.vue";
import RegenFeedbackModal from "./RegenFeedbackModal.vue";

const scriptStore = useScriptStore();
const workspaceStore = useWorkspaceStore();

const STORYBOARD_STEP_INDEX = PIPELINE_STEPS.findIndex((s) => s.key === "storyboard");
const router = useRouter();
const projectStore = useProjectStore();

const { startPolling } = useStagePolling({
  loadSnapshot: () => scriptStore.loadActiveScriptSnapshot(),
  isGenerating: (snapshot) =>
    snapshot.current_status === "script_generating" ||
    snapshot.active_script?.execution_state?.generating === true,
  isTerminal: (snapshot) => {
    if (snapshot.current_status === "script_failed") return true;
    if (!snapshot.active_script) return false;
    // generating 占位记录不算终态
    if (snapshot.active_script.execution_state?.generating) return false;
    // 有真实 script_text 且状态不是 generating
    return !!snapshot.active_script.script_text;
  },
});

onMounted(async () => {
  await scriptStore.loadActiveScriptSnapshot();
  // F5 恢复：如果 snapshot 显示 generating，启动轮询
  const s = scriptStore.state.snapshot;
  if (
    s?.current_status === "script_generating" ||
    s?.active_script?.execution_state?.generating
  ) {
    startPolling();
  }
  await triggerAutoGenerate();
});

let autoGenerated = false;

/** Auto-generate script when snapshot shows ready state but no active script. */
async function triggerAutoGenerate() {
  if (autoGenerated) return;
  const s = scriptStore.state.snapshot;
  if (
    s &&
    !s.active_script &&
    (s.current_status === "script_pending" || s.current_status === "script_ready") &&
    !scriptStore.state.isLoading &&
    !scriptStore.state.loadError
  ) {
    autoGenerated = true;
    startPolling();
    await scriptStore.generateInitialScript();
    if (!scriptStore.state.loadError) {
      ElMessage.success("文案已生成");
    }
  }
}

// Also trigger on snapshot change (handles timing where projectId is set after mount)
watch(() => scriptStore.state.snapshot, async (snapshot) => {
  if (snapshot && !snapshot.active_script && !autoGenerated) {
    await triggerAutoGenerate();
  }
});

/** Resolve the visible script: selected history entry > active snapshot > fallback from history. */
const visibleScript = computed(() => {
  const selected = scriptStore.state.history.find(
    (entry) => entry.entry_id === scriptStore.state.selectedHistoryEntryId,
  );
  if (selected) return selected.script;

  if (scriptStore.state.snapshot?.active_script) {
    return scriptStore.state.snapshot.active_script;
  }

  if (
    scriptStore.state.snapshot?.current_status === "script_reviewing" ||
    scriptStore.state.snapshot?.current_status === "script_failed"
  ) {
    return scriptStore.state.history[0]?.script ?? null;
  }

  return null;
});

const isGenerating = computed(
  () =>
    scriptStore.state.snapshot?.current_status === "script_generating" ||
    scriptStore.state.snapshot?.active_script?.execution_state?.generating === true,
);

const isGenerationFailed = computed(
  () =>
    scriptStore.state.snapshot?.current_status === "script_failed",
);

const isInitialScriptLoading = computed(
  () => scriptStore.state.isLoading && !visibleScript.value,
);

const displayScriptText = computed(() => {
  const text = visibleScript.value?.script_text ?? "";

  if (text.includes("\n")) {
    return text.replace(/\n{3,}/g, "\n\n").replace(/\n(?!\n)/g, "\n\n").replace(/\n{3,}/g, "\n\n");
  }

  const sentences = text.split(/(?<=[。！？])(?=[^。！？])/);
  if (sentences.length <= 2) return text;

  const paragraphs: string[] = [];
  for (let i = 0; i < sentences.length; i += 2) {
    const chunk = sentences.slice(i, i + 2).join("");
    if (chunk.trim()) paragraphs.push(chunk);
  }
  return paragraphs.join("\n\n");
});

/** Build review soft issues list from semantic_review for display. */
const reviewIssues = computed(() => {
  const s = visibleScript.value;
  if (!s?.semantic_review) return [];

  const issues: Array<{ code: string; message: string }> = [];

  if (s.semantic_review.summary) {
    issues.push({ code: "review_summary", message: s.semantic_review.summary });
  }

  const softIssues = s.semantic_review.soft_issues ?? [];
  for (const item of softIssues) {
    if (typeof item === "string") {
      issues.push({ code: "", message: item });
    } else {
      issues.push({ code: item.code ?? "", message: item.message ?? "" });
    }
  }

  return issues;
});

const reviewDecision = computed(() => {
  const s = visibleScript.value;
  if (!s) return null;
  if (s.semantic_review?.decision) return s.semantic_review.decision;
  if (s.local_validation?.decision) return s.local_validation.decision;
  return null;
});

const scriptWordCount = computed(() => {
  const text = visibleScript.value?.script_text ?? "";
  return text.replace(/\s/g, "").length;
});

const scriptDurationSec = computed(() => {
  return visibleScript.value?.estimated_duration_sec ?? 0;
});

const scriptDurationLabel = computed(() => {
  const sec = scriptDurationSec.value;
  if (!sec) return "—";
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  return m > 0 ? `约${m}分${s}秒` : `约${s}秒`;
});

const visibleScriptVersionLabel = computed(() => {
  const total = scriptStore.state.history.length;
  if (total === 0) return "首稿";
  const selected = historyEntries.value.find(
    (e) => e.entry_id === scriptStore.state.selectedHistoryEntryId,
  );
  if (selected) return selected.versionLabel;
  return total === 1 ? "首稿" : `V${total}`;
});

const isViewingHistoryEntry = computed(() => {
  const entries = scriptStore.state.history;
  if (entries.length === 0) return false;
  return scriptStore.state.selectedHistoryEntryId !== entries[0]?.entry_id;
});

const viewingHistoryLabel = computed(() => {
  if (!isViewingHistoryEntry.value) return null;
  const entry = historyEntries.value.find(
    (e) => e.entry_id === scriptStore.state.selectedHistoryEntryId,
  );
  if (!entry) return null;
  return entry.versionLabel;
});

const scriptCreatedAtLabel = computed(() => {
  const iso = visibleScript.value?.created_at;
  if (!iso) return null;
  const d = new Date(iso);
  const now = new Date();
  const isToday = d.toDateString() === now.toDateString();
  const time = d.toLocaleTimeString("zh-CN", { hour: "2-digit", minute: "2-digit" });
  if (isToday) return `今天 ${time}`;
  return `${d.getMonth() + 1}/${d.getDate()} ${time}`;
});

function formatHistoryTime(iso?: string) {
  if (!iso) return null;
  const d = new Date(iso);
  const now = new Date();
  const isToday = d.toDateString() === now.toDateString();
  const time = d.toLocaleTimeString("zh-CN", { hour: "2-digit", minute: "2-digit" });
  if (isToday) return `今天 ${time}`;
  return `${d.getMonth() + 1}/${d.getDate()} ${time}`;
}

function historyReviewBadge(decision?: string) {
  if (decision === "pass") return { text: "通过", type: "success" as const };
  if (decision === "regen_once") return { text: "建议重生成", type: "warning" as const };
  if (decision === "hard_fail") return { text: "未通过", type: "danger" as const };
  return { text: "审校中", type: "info" as const };
}

function historyPreview(text: string) {
  return text.replace(/\s/g, "").slice(0, 40);
}

const ISSUE_CODE_MAP: Record<string, string> = {
  scene_enhancement: "场景细节",
  dialogue_enhancement: "对话细节",
  opening_hook_weak: "开篇冲击力",
  pace_too_slow: "节奏偏慢",
  pace_too_fast: "节奏偏快",
  emotional_depth: "情感厚度",
  character_depth: "人物刻画",
  ending_weak: "结尾力度",
  script_body_too_thin: "篇幅偏薄",
  conflict_pressure: "冲突压力",
};

function humanizeIssueCode(code: string) {
  return ISSUE_CODE_MAP[code] ?? code;
}

const historyEntries = computed(() => {
  const total = scriptStore.state.history.length;
  return scriptStore.state.history.map((entry, idx) => {
    const versionNum = total - idx;
    return {
      entry_id: entry.entry_id,
      label: entry.label,
      version: versionNum,
      versionLabel: versionNum === 1 ? "首稿" : `V${versionNum}`,
      script_text: entry.script.script_text,
      word_count: entry.script.script_text.replace(/\s/g, "").length,
      review_decision: entry.script.review_decision,
      created_at: entry.script.created_at,
      execution_state: entry.script.execution_state,
    };
  });
});

const showRegenModal = ref(false);
const isRegenerating = ref(false);
const historyOpen = ref(false);

function toggleHistory() {
  historyOpen.value = !historyOpen.value;
}

async function handleRegenSubmit(userFeedback: string) {
  isRegenerating.value = true;
  try {
    await scriptStore.runRegenOnce(userFeedback || undefined);
    if (!scriptStore.state.loadError) {
      ElMessage.success("文案重新生成完成");
    }
  } finally {
    isRegenerating.value = false;
  }
}

function handleRetry() {
  scriptStore.retryLoadActiveScriptSnapshot();
}

function handleSelectHistory(entryId: string) {
  scriptStore.selectHistoryEntry(entryId);
}

function handleConfirm() {
  ElMessage.success("文案已确认，进入分镜规划");
  workspaceStore.setCurrentStep(STORYBOARD_STEP_INDEX);
  const pid = projectStore.state.projectId; if (pid) router.push(`/projects/${pid}/storyboard`);
}
</script>

