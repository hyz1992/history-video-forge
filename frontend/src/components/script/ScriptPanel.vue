              <span
                v-if="issue.code === 'review_summary'"
                class="script-review-summary"
              ><span class="script-review-issue-code">摘要</span>{{ issue.message }}</span>
              <template v-else>
                <span
                  v-if="issue.code"
                  class="script-review-issue-code"
                >{{ humanizeIssueCode(issue.code) }}</span>
                <span class="script-review-issue-msg">{{ issue.message }}</span>
              </template>
            </div>
          </div>

          <!-- Action buttons -->
          <div v-if="visibleScript && !isViewingHistoryEntry" class="script-actions-card">
            <el-button
              type="primary"
              :disabled="scriptStore.state.isRunningAction"
              @click="handleConfirm"
              class="script-confirm-btn"
            >
              确认文案，进入分镜规划
            </el-button>
          </div>
        </div>
      </div>
    </template>

    <RegenFeedbackModal
      :visible="showRegenModal"
      :script="visibleScript"
      @update:visible="showRegenModal = $event"
      @submit="handleRegenSubmit"
    />

    <StageLoadingBar
      :visible="isRegenerating"
      text="重新生成中…"
    />
  </div>
</template>

